"""Usage: python3 make_gstore_qr.py app/src/main/res/drawable/ic_gstore_qr.xml

Needs `pip install qrcode`. Draws the GStore download link as a plain QR VectorDrawable.
"""
import sys

import qrcode

URL = 'https://disk.yandex.ru/d/bJoMhjqGw8rMtg'
QUIET = 4


def module_paths(matrix):
    """Black runs as one path per few rows; lint flags paths longer than 800 characters."""
    paths = []
    parts = []
    for row, cells in enumerate(matrix):
        if row % 5 == 0 and parts:
            paths.append(''.join(parts))
            parts = []
        col = 0
        while col < len(cells):
            if not cells[col]:
                col += 1
                continue
            start = col
            while col < len(cells) and cells[col]:
                col += 1
            parts.append('M%s,%sh%sv1h-%sz' % (start + QUIET, row + QUIET, col - start,
                                               col - start))
    paths.append(''.join(parts))
    return paths


def main():
    code = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
    code.add_data(URL)
    code.make(fit=True)
    matrix = code.get_matrix()
    size = len(matrix) + 2 * QUIET
    with open(sys.argv[1], 'w') as out:
        out.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- %s, generated by tools/make_gstore_qr.py; rerun it instead of editing. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="%sdp"
    android:height="%sdp"
    android:viewportWidth="%s"
    android:viewportHeight="%s">
    <path
        android:fillColor="#FFFFFF"
        android:pathData="M0,0h%sv%sh-%sz" />
%s</vector>
''' % (URL, size * 4, size * 4, size, size, size, size, size, ''.join('''    <path
        android:fillColor="#000000"
        android:pathData="%s" />
''' % path for path in module_paths(matrix))))


if __name__ == '__main__':
    main()
